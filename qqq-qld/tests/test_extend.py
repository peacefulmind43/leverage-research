"""Tests for the pre-inception history reconstruction."""

import numpy as np
import pandas as pd
import pytest

from qqq_qld.extend import (
    calibrate_synthetic,
    calibration_report,
    extend_history,
    stress_episodes,
)

ER_QQQ = 0.0020
ER_QLD = 0.0095


def scenario(dividend_yield=0.008, swap_spread=0.011, rf=0.03, days=2520, seed=1):
    """Index history plus the fund returns it implies, with known parameters."""
    dates = pd.bdate_range("2000-01-03", periods=days)
    rng = np.random.default_rng(seed)
    index_returns = pd.Series(rng.normal(0.0004, 0.013, days), index=dates)
    risk_free = pd.Series(rf, index=dates)
    total = index_returns + dividend_yield / 252
    funds = pd.DataFrame(
        {
            "QQQ": total - ER_QQQ / 252,
            "QLD": 2 * total - (rf + swap_spread) / 252 - ER_QLD / 252,
        }
    )
    return index_returns, risk_free, funds


def test_calibration_recovers_known_parameters():
    index_returns, risk_free, funds = scenario()
    calibration = calibrate_synthetic(funds, index_returns, risk_free)
    assert np.isclose(calibration["dividend_yield"], 0.008, atol=1e-9)
    assert np.isclose(calibration["swap_spread"], 0.011, atol=1e-9)


def test_reconstruction_reproduces_the_funds_it_was_calibrated_on():
    index_returns, risk_free, funds = scenario()
    calibration = calibrate_synthetic(funds, index_returns, risk_free)
    fit = calibration_report(funds, index_returns, risk_free, calibration)
    # Exact here because the scenario is generated by the same mechanics the
    # reconstruction assumes; on real data the informative check is that the
    # correlation and drawdown columns stay close, not that they are identical.
    assert (fit["correlation"] > 0.9999).all()
    assert np.allclose(fit["real_cagr"], fit["synthetic_cagr"], atol=1e-6)
    assert np.allclose(fit["real_max_drawdown"], fit["synthetic_max_drawdown"], atol=1e-6)


def test_extend_history_prefers_real_returns_and_only_prepends():
    index_returns, risk_free, funds = scenario()
    live = funds.iloc[1260:]
    combined, meta = extend_history(live, index_returns, risk_free)
    assert combined.index.min() == index_returns.index.min()
    assert len(combined) > len(live)
    assert meta["splice_date"] == str(live.index.min().date())
    # Live rows must survive untouched: the reconstruction fills only the gap.
    pd.testing.assert_frame_equal(combined.loc[live.index], live)


def test_extend_history_requires_index_to_predate_the_funds():
    index_returns, risk_free, funds = scenario()
    with pytest.raises(ValueError, match="does not predate"):
        extend_history(funds, index_returns, risk_free)


def test_calibration_requires_enough_overlap():
    index_returns, risk_free, funds = scenario()
    with pytest.raises(ValueError, match="overlap"):
        calibrate_synthetic(funds.iloc[:100], index_returns, risk_free)


def test_stress_drawdowns_deepen_with_leverage():
    """The property the drawdown table exists to show, asserted directly."""
    index_returns, risk_free, funds = scenario(days=1260, seed=7)
    episodes = {"window": (str(funds.index.min().date()), str(funds.index.max().date()))}
    table = stress_episodes(funds, weights=(0.0, 0.3, 1.0), episodes=episodes)
    row = table.loc["window"]
    assert row["qld_0%"] > row["qld_30%"] > row["qld_100%"]
